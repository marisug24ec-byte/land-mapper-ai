export function coordsToMeasurement(coords: L.LatLng[], confidence = 90): Measurement | null {
  if (coords.length < 3) return null;
  try {
    const ring = coords.map(c => [c.lng, c.lat]);
    ring.push([coords[0].lng, coords[0].lat]);
    const poly = turf.polygon([ring]);
    const area = turf.area(poly);
    const line = turf.lineString(ring);
    const perimeter = turf.length(line, { units: 'meters' });
    return { areaSqm: area, areaAcres: area * 0.000247105, areaHectares: area * 0.0001, perimeterM: perimeter, confidence };
  } catch {
    return null;
  }
}

export function geoJsonToMeasurement(geoJson: any, confidence = 85): Measurement | null {
  try {
    const area = turf.area(geoJson);
    const line = turf.polygonToLine(geoJson);
    const perimeter = turf.length(line, { units: 'meters' });
    return { areaSqm: area, areaAcres: area * 0.000247105, areaHectares: area * 0.0001, perimeterM: perimeter, confidence };
  } catch {
    return null;
  }
}

export function circleMeasurement(radiusM: number): Measurement {
  const area = Math.PI * radiusM * radiusM;
  const perimeter = 2 * Math.PI * radiusM;
  return { areaSqm: area, areaAcres: area * 0.000247105, areaHectares: area * 0.0001, perimeterM: perimeter, confidence: 95 };
}

export function getSegRadius(zoom: number): number {
  return Math.max(15, Math.min(400, 50 * Math.pow(2, 16 - zoom)));
}

/** Compute advanced confidence for AI segmentation */
export function computeSegmentationConfidence(
  includeCount: number,
  excludeCount: number,
  zoom: number,
  areaHectares: number
): number {
  // Edge strength: higher zoom = better edges
  const edgeScore = Math.min(1, (zoom - 14) / 6) * 30;
  // Seed density: more points = higher confidence
  const seedScore = Math.min(1, includeCount / 8) * 25;
  // Exclusion refinement bonus
  const exclusionScore = Math.min(1, excludeCount / 4) * 15;
  // Area reasonableness: 0.01–50 hectares is reasonable
  const areaScore = (areaHectares > 0.01 && areaHectares < 50) ? 15 : 5;
  // Base score
  const base = 15;

  return Math.min(97, Math.round(base + edgeScore + seedScore + exclusionScore + areaScore));
}

export function exportPdf(measurement: Measurement) {
  const doc = new jsPDF();

  doc.setFontSize(24);
  doc.setTextColor(59, 130, 246);
  doc.text('AL-Scout 3D', 20, 25);

  doc.setFontSize(12);
  doc.setTextColor(100);
  doc.text('Scouting Report — Ashok Leyland', 20, 35);
  doc.text(`Generated: ${new Date().toLocaleString()}`, 20, 45);

  doc.setDrawColor(59, 130, 246);
  doc.line(20, 52, 190, 52);

  doc.setFontSize(16);
  doc.setTextColor(30);
  doc.text('Measurement Results', 20, 65);

  doc.setFontSize(12);
  doc.setTextColor(60);
  doc.text(`Area: ${measurement.areaSqm.toFixed(2)} sq.m`, 25, 80);
  doc.text(`Area: ${measurement.areaAcres.toFixed(4)} Acres`, 25, 90);
  doc.text(`Area: ${measurement.areaHectares.toFixed(4)} Hectares`, 25, 100);
  doc.text(`Perimeter: ${measurement.perimeterM.toFixed(2)} m`, 25, 110);
  doc.text(`Confidence: ${measurement.confidence}%`, 25, 120);

  doc.line(20, 135, 190, 135);

  doc.setFontSize(14);
  doc.setTextColor(200, 60, 60);
  doc.text('DISCLAIMER', 20, 148);

  doc.setFontSize(9);
  doc.setTextColor(100);
  const lines = [
    'This report is generated by AL-Scout 3D for preliminary site assessment only.',
    'This is NOT a legal land survey and should not be used for legal purposes.',
    'It does NOT use official government land records or cadastral data.',
    'Accuracy depends on satellite imagery quality and edge clarity.',
    'Works best with clear boundaries (roads, rivers, vegetation edges).',
    'May perform poorly in dense urban areas.',
    'For official surveys, consult a licensed land surveyor.',
  ];
  lines.forEach((l, i) => doc.text(l, 20, 158 + i * 7));

  doc.save('al-scout-3d-report.pdf');
}

export function saveProject(layers: any[], measurement: Measurement | null, mode: string) {
  const project = { id: Date.now().toString(), timestamp: Date.now(), mode, layers, measurement };
  const saved = JSON.parse(localStorage.getItem('alscout_projects') || '[]');
  saved.push(project);
  localStorage.setItem('alscout_projects', JSON.stringify(saved));
}
